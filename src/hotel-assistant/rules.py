# -*- coding: utf-8 -*-
"""
rules.py — 对话违规自动标记（确定性关键词规则，不交给模型判断）

设计要点：
  · 规则即代码：每条规则给出类别、触发词、标记原因；
  · 命中任意关键词即标记，返回 (True, 原因)；管理员可人工改判（审计页）；
  · 客人消息与员工回复都会过一遍——客人问"能不能不查房就卖"也要被看见。
"""

# (类别, 触发词列表, 标记原因)
VIOLATION_RULES = [
    ("查房绕过", ["不查房", "不用复查", "直接标可售", "先卖后查", "跳过检查"],
     "试图绕过三态闸门（查房）"),
    ("OOO绕过", ["直接解除封锁", "不复查就恢复", "跳过异味复查"],
     "试图绕过维修房解除封锁硬拦截"),
    ("隐私违规", ["客人身份证号", "客人手机号", "客人姓名", "客人电话", "客人信息"],
     "涉及客人隐私信息"),
    ("审计规避", ["删掉记录", "不留痕", "借账号", "不用具名", "跳过审计"],
     "试图规避具名确认与审计"),
]


def check_violation(text: str) -> tuple[bool, str]:
    """
    检查文本是否命中违规规则。

    :return: (是否违规, 标记原因)。未命中返回 (False, "")。
    """
    for category, keywords, reason in VIOLATION_RULES:
        for kw in keywords:
            if kw in text:
                return True, f"[{category}] {reason}（命中词：{kw}）"
    return False, ""
