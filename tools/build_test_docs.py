def build_scene(key: str, idx: int) -> None:
    cfg = SCENES[key]
    d = load()
    cases = [r for r in d["results"] if r["scene"].startswith(key)]
    doc = Doc(
        f"{cfg['file']}",
        f"酒店房态与入住协同 MVP · {cfg['sub']}",
        [
            f"文档编号：HRSC-TEST-{idx:02d}",
            "被测系统：src/room-status-mvp（v1.0.0）",
            f"本场景用例：{len(cases)} 条，通过 {sum(1 for c in cases if c['pass'])} 条",
            "证据：接口实测 + 页面实拍（Edge headless）",
            "编制日期：2026 年 11 月 6 日",
        ],
    )

    doc.h1("一、场景定义与测试目标")
    doc.p(f"本场景属于五类场景中的「{key}」类。之所以单独成册，是因为这一类问题在真实门店里"
          f"不是「会不会发生」，而是「发生了几次、有没有被记录」。以下四点是要验证的对象：")
    doc.bullets(cfg["goal"])

    doc.h1("二、判定标准")
    doc.table(["判定项", "通过标准"], cfg["criteria"],
              caption=f"表 2-1　{key}场景判定标准", widths=(4.4, 11.4), align_center=False)

    doc.h1("三、测试环境与数据")
    doc.table(
        ["项", "说明"],
        [
            ["实例", ":8103 基线（干净数据 24 间房）" + ("　/　:8102 故障注入" if key == "故障" else "")
                     + ("　/　:8101 截图实例" if key != "故障" else "　/　:8109 未监听")],
            ["账号", "front / Front@123　house / House@123　qa / Qa@123　admin / Admin@123"],
            ["数据复位", "用例按状态动态探测房间并沿状态机驱动到所需状态，不写死房号，可反复执行"],
            ["证据形式", "接口矩阵（状态码 + 业务码 + 耗时）与页面实拍（含接口证据面板）"],
        ],
        caption="表 3-1　环境与数据",
        widths=(2.8, 13.0),
    )

    doc.h1("四、测试过程")
    doc.p("下表按实际操作顺序记录：每一步都在真实实例上执行，请求列给出实际接口，"
          "实际列记录系统真实返回（不是预期值的复述）。")
    doc.table(["步", "操作", "接口 / 路径", "预期", "实际结果", "结论"], cfg["steps"],
              caption=f"表 4-1　{key}场景执行过程", widths=(0.9, 4.4, 3.6, 3.2, 4.4, 1.2),
              size=8, align_center=False)

    doc.h1("五、过程截图")
    doc.p("以下截图由 Edge headless 驱动真实浏览器拍摄；带「接口证据面板」的图，其请求、状态码与返回体"
          "均为当时真实调用结果，未做任何拼接或美化。")
    for rel, cap in cfg["images"]:
        p = SHOT / rel
        if p.exists():
            doc.image(str(p), cap, width_cm=15.2)

    doc.h1("六、结论")
    for i, line in enumerate(cfg["conclusion"], 1):
        doc.p(f"（{i}）{line}")
    doc.note(f"本场景 {len(cases)} 条用例全部通过；逐条记录见《测试方案》附录 A，"
             f"整体 53 条用例 100% 通过。")

    doc.save(TD / f"{cfg['file']}.docx")
    print("saved", f"{cfg['file']}.docx")


